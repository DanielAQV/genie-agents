"""루프가 갈리는 자리 — 이름을 붙이고 기본값을 준다.

━━ 왜 이 파일이 있나 ━━

에이전트 둘을 나란히 놓고 도구 루프를 재봤더니 86줄 대 84줄에 67% 가 같았다.
같은 뼈대인데 **갈리는 33% 가 코드 곳곳에 흩어져 있어서 비교가 안 됐다.**
어느 쪽이 무엇을 다르게 하는지 알려면 두 파일을 나란히 놓고 읽어야 했다.

여기 올려 두면 셋이 된다.

  1. **아무것도 안 정하면 똑같이 작동한다.** 기본값이 하나라서다.
  2. 다르게 하려면 **한 파일에 눈에 보이게** 적어야 한다.
  3. 고를 것이 목록으로 존재하므로 **골라서 쓰는 사람**에게 줄 수 있다.

━━ `if agent == "이름"` 을 쓰지 않는 이유 ━━

분기는 **누가 정했는지를 안 말한다.** 다음 사람이 그 줄을 보고 뒤집을 수 있고,
뒤집어도 아무도 모른다. 여기 값으로 적히면 그 자리가 곧 기록이다 —

    voice_reply=True,   # 소리로 답한다. 본인이 그렇게 정했다(2026-08-29)

━━ 여기 없는 것 ━━

무엇을 말할지, 무슨 도구를 가질지, 어떤 원칙을 세울지는 여기서 안 정한다.
이 파일이 정하는 것은 **루프가 도는 모양**뿐이다.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field

# 글을 다듬는 손. (글) → (다듬은 글, 걷어낸 것들)
Sanitizer = Callable[[str], "tuple[str, list[str]]"]


@dataclass(frozen=True)
class Policy:
    """루프의 모양. 전부 기본값이 있고, 기본값끼리는 서로 같다."""

    # ── 한도 ────────────────────────────────────────────────────────
    max_turns: int = 8
    """도구를 이만큼 돌면 끊는다. 한 번 깨어난 것이 무한히 돌지 않게."""

    max_tokens: int = 4096
    """한 응답의 상한. 모델 한도에 맞춘다."""

    # ── 도구를 부르는 턴에 같이 온 글 ───────────────────────────────
    keep_text_with_tool_call: bool = False
    """**기본은 버린다.**

    도구를 부르기 직전에 붙는 "찾아볼게" 같은 말이거나 내부 상태를 정리한
    혼잣말이다. 실제로 그런 줄이 그대로 사람에게 나간 적이 있다 — 그 턴은
    도구를 셋 부르고 마지막 호출이 글 없이 끝나서, 덮을 것이 없어 그 줄이
    답 자리에 남았다.

    진짜 하려던 말이면 마지막 응답에서 다시 나온다. 안 나오면 원래 답이
    아니었던 것이다.
    """

    sanitizers: tuple[Sanitizer, ...] = ()
    """모델이 낸 글에서 걷어낼 것들. 순서대로 지나간다.

    **무엇을 걷어낼지는 에이전트마다 다르다** — 없는 파일을 가리키는 표시,
    도구를 글로 흉내 낸 대목 같은 것들이다. 걷어낸 것은 로그에 남는다.
    """

    retry_when_empty: bool = True
    """다듬고 났더니 남는 글이 없으면 **한 번만** 다시 묻는다.

    도구는 다 돌았는데 답이 한 글자도 없는 자리다. 사람 쪽에서는 안 온 것과
    구분이 안 된다. 같은 입력을 그대로 다시 보내므로 대개 캐시 적중이다.
    **한 번뿐이다** — 두 번 이상 걸리면 여기서 풀 문제가 아니고, 재시도가
    그만큼 값을 태운다.
    """

    # ── 언제 끝내나 ─────────────────────────────────────────────────
    decision_tools: frozenset[str] = frozenset()
    """이 도구가 불리면 **거기서 끝낸다.**

    판단이 그 안에서 끝난 자리다. 뒤이은 호출은 아무도 안 읽는 마무리 문장
    하나를 받으려고 입력 전체를 다시 보내는 것뿐이다.

    ★ **부른 것과 선 것은 다르다.** 도구가 막혀서 아무것도 안 남기고
      되돌아왔으면 판단이 안 선 것이다 — 그걸 판단으로 치고 끊으면 그 자리는
      판단 없이 끝난다. 막힌 것은 `blocked` 로 온다.
    """

    decision_scopes: frozenset[str] = frozenset()
    """판단 도구로 끊는 것을 이 자리에서만 한다. 비어 있으면 어디서나."""

    max_pauses: int = 0
    """서버 도구가 자기 한도에 걸려 턴을 끊었을 때(`pause_turn`) 이어붙이는 횟수.

    그대로 다시 보내면 이어서 돈다 — "계속해" 같은 말을 덧붙이면 안 된다.
    그 기능이 없는 모델에서는 0 이고, 0 이면 이 자리가 아예 안 돈다.
    """

    # ── 캐시 ────────────────────────────────────────────────────────
    move_cache_edge: bool = True
    """도구 루프는 같은 것을 n+1번 보낸다. 자라는 건 도구 결과뿐인데 경계가
    앞쪽 하나뿐이면 그 뒤가 매 요청 새로 나간다.

    ★ 이 표시를 무시하는 모델이 있다. 무시하는 어댑터는 그렇다고 첫머리에
      적어라 — 안 적으면 도는 줄 알고 유지보수한다.
    """

    cache_ttl: str = "5m"
    """경계에 거는 TTL. 루프는 초 단위로 끝나므로 짧은 쪽이 싸다."""

    # ── 강제 ────────────────────────────────────────────────────────
    force_first: str = ""
    """첫 요청에서만 이 도구를 **반드시** 부르게 한다.

    그 턴에만 있는 것을 놓치지 않게 하는 자리다(예: 그림은 그 턴에만 손에
    있고, 적어 두지 않으면 다음 턴에 사라진다). 한 번만 걸리고 풀린다.
    """

    extra: dict = field(default_factory=dict)
    """모델에 그대로 넘길 것. 어댑터가 모르는 키는 무시한다."""


DEFAULT = Policy()
"""아무것도 안 정했을 때. **두 에이전트가 이걸 쓰면 똑같이 작동한다.**"""
